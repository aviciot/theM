#!/usr/bin/env python3.12
"""Generate docs/reference/*-generated.md.  stdlib only, deterministic output (no timestamps).

  gen_reference.py routes [--check]       static scan of Go chi route registrations (no stack needed)
  gen_reference.py schema [--check]       live Postgres catalog via `docker exec them-postgres psql` (needs the stack)
  gen_reference.py node-types [--check]   GET /api/v1/admin/node-types (needs the stack + ADMIN_USER/ADMIN_PASSWORD)
  gen_reference.py redis [--check]        static scan of Go for Redis key/channel literals (no stack needed)
  gen_reference.py redis-live             report-only: key patterns seen in the running Redis that the static scan did not find

--check regenerates in memory and exits 1 when the committed file differs (CI uses it for `routes`).
Generated files carry `generated: true` and must never be edited by hand.
"""
import json, os, re, subprocess, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
FM = "---\ntitle: {title}\ntype: reference\nstatus: current\nlast_verified: generated\ngenerated: true\n---\n\n<!-- GENERATED by scripts/gen_reference.py {cmd} — do not edit by hand -->\n\n"


def write(name, cmd, title, body, check):
    path = OUT / name
    text = FM.format(title=title, cmd=cmd) + body.rstrip("\n") + "\n"
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            print(f"{name}: OUT OF DATE — run: python3.12 scripts/gen_reference.py {cmd}")
            return 1
        print(f"{name}: up to date")
        return 0
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")
    return 0


# ── routes (static) ──────────────────────────────────────────────────────────
ROUTE = re.compile(r'\b(\w+)\.(Get|Post|Put|Patch|Delete|Head|Options|Handle|HandleFunc|Mount|Route|Method)\(\s*(?:"[A-Z]+"\s*,\s*)?"(/[^"]*)"')


def routes(check):
    rows = set()
    for f in sorted((ROOT / "go").rglob("*.go")):
        rel = f.relative_to(ROOT).as_posix()
        if "/vendor/" in rel or rel.endswith("_test.go"):
            continue
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.lstrip().startswith("//"):
                continue
            for m in ROUTE.finditer(line):
                rows.add((rel, m.group(2).upper(), m.group(3)))
    rows = sorted(rows)
    body = ["# HTTP route registrations (generated)", "",
            "Static scan of chi registrations in `go/` (non-test). Paths are **relative to the router they are "
            "registered on**; `Mount`/`Route` rows show where a sub-router is attached. Use "
            "`docs/architecture/platform-overview.md` for external prefixes. Not a substitute for hitting the live route "
            "(see the route-ownership rule in `go/CLAUDE.md`).", "",
            f"{len(rows)} registrations.", "", "| File | Verb | Path |", "|---|---|---|"]
    body += [f"| `{r[0]}` | {r[1]} | `{r[2]}` |" for r in rows]
    return write("routes-generated.md", "routes", "HTTP Route Registrations (generated)", "\n".join(body), check)


# ── schema (live) ────────────────────────────────────────────────────────────
def psql(sql):
    r = subprocess.run(["docker", "exec", "them-postgres", "psql", "-U", "them", "-d", "them", "-At", "-F", "\x1f", "-c", sql],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("psql failed: " + r.stderr.strip())
    return [ln.split("\x1f") for ln in r.stdout.strip("\n").split("\n") if ln]


def schema(check):
    tables = psql("""select n.nspname, c.relname, c.relrowsecurity, c.relforcerowsecurity, pg_get_userbyid(c.relowner)
                     from pg_class c join pg_namespace n on n.oid=c.relnamespace
                     where n.nspname in ('them','auth_service') and c.relkind='r' order by 1,2""")
    cols = psql("""select table_schema, table_name, column_name, data_type, is_nullable, coalesce(column_default,'')
                   from information_schema.columns where table_schema in ('them','auth_service') order by 1,2,ordinal_position""")
    pols = psql("""select schemaname, tablename, policyname, cmd, roles::text from pg_policies
                   where schemaname in ('them','auth_service') order by 1,2,3""")
    bycol = {}
    for s, t, c, dt, nul, d in cols:
        bycol.setdefault((s, t), []).append((c, dt, nul, d))
    polby = {}
    for s, t, p, cmd, roles in pols:
        polby.setdefault((s, t), []).append(f"{p} ({cmd}, {roles})")
    body = ["# Database schema (generated from the live catalog)", "",
            "Schemas `them` and `auth_service`. `RLS` = row-level security enabled, `FORCE` = forced for the table owner. "
            "Defaults are abbreviated. Source of truth is the running database, **not** `db/001_schema.sql`.", "",
            f"{len(tables)} tables.", ""]
    for s, t, rls, force, owner in tables:
        flag = ("RLS+FORCE" if force == "t" else "RLS" if rls == "t" else "no RLS")
        body += [f"## {s}.{t}", "", f"Owner `{owner}` · {flag}", "", "| Column | Type | Null | Default |", "|---|---|---|---|"]
        for c, dt, nul, d in bycol.get((s, t), []):
            d = (d[:40] + "…") if len(d) > 41 else d
            body.append(f"| `{c}` | {dt} | {'yes' if nul == 'YES' else 'no'} | {('`' + d.replace('|', '\\|') + '`') if d else ''} |")
        for p in polby.get((s, t), []):
            body.append(f"\nPolicy: {p}")
        body.append("")
    return write("schema-generated.md", "schema", "Database Schema (generated from live catalog)", "\n".join(body), check)


# ── node types (live API) ────────────────────────────────────────────────────
def node_types(check):
    user, pw = os.environ.get("ADMIN_USER"), os.environ.get("ADMIN_PASSWORD")
    base = os.environ.get("THE_M_BASE_URL", "http://localhost:8088")
    if not user or not pw:
        sys.exit("set ADMIN_USER and ADMIN_PASSWORD (and optionally THE_M_BASE_URL) for node-types")
    req = urllib.request.Request(base + "/auth/api/v1/auth/login", json.dumps({"username": user, "password": pw}).encode(),
                                 {"Content-Type": "application/json"})
    tok = json.load(urllib.request.urlopen(req))["access_token"]
    req = urllib.request.Request(base + "/api/v1/admin/node-types", headers={"Authorization": "Bearer " + tok})
    data = json.load(urllib.request.urlopen(req))
    items = data if isinstance(data, list) else data.get("node_types", data.get("items", []))
    body = ["# Canvas node types (generated from GET /api/v1/admin/node-types)", "", f"{len(items)} node types.", "",
            "| Type | Label | Family | Executable | Source | Sink | Output arity |", "|---|---|---|---|---|---|---|"]
    for n in sorted(items, key=lambda x: (str(x.get("family", "")), str(x.get("type", "")))):
        body.append(f"| `{n.get('type')}` | {n.get('label', '')} | {n.get('family', '')} | {n.get('executable', '')} | "
                    f"{n.get('is_source', '')} | {n.get('is_sink', '')} | {n.get('output_arity', '')} |")
    return write("node-types-generated.md", "node-types", "Canvas Node Types (generated)", "\n".join(body), check)


# ── redis (static + live drift report) ───────────────────────────────────────
KEYLIT = re.compile(r'"((?:them|rl):[A-Za-z0-9_:{}%.<>\-]*)"')
UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")
HEX = re.compile(r"\b[0-9a-f]{16,}\b")


def redis(check):
    found = {}
    for f in sorted((ROOT / "go").rglob("*.go")):
        rel = f.relative_to(ROOT).as_posix()
        if "/vendor/" in rel or rel.endswith("_test.go"):
            continue
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.lstrip().startswith("//"):
                continue
            for m in KEYLIT.finditer(line):
                found.setdefault(m.group(1), set()).add(rel)
    groups = {}
    for lit in sorted(found):
        parts = lit.split(":")
        top = ":".join(parts[:2]) if parts[0] == "them" and len(parts) > 1 else parts[0]
        groups.setdefault(top, []).append(lit)
    body = ["# Redis keys and channels (generated)", "",
            "Static scan of string literals starting with `them:` or `rl:` in non-test Go code. A literal is often only the "
            "**prefix** of a key built by concatenation (e.g. `them:ep:` + slug + `:sessions`) or a `fmt` pattern "
            "(`%s` = the variable part). Treat this as the authoritative list of *where* keys are defined; read the "
            "listed file for the full shape, TTL and owner. Narrative: `docs/architecture/*.md` (gate/session in "
            "`run-lifecycle.md`, MCP keys in `mcp-service.md`, auth cache in `auth-and-roles.md`). "
            "Drift against the running Redis: `python3.12 scripts/gen_reference.py redis-live`.", "",
            f"{len(found)} literals in {len(groups)} groups.", ""]
    for top in sorted(groups):
        body += [f"## `{top}`", "", "| Literal | Defined in |", "|---|---|"]
        for lit in groups[top]:
            body.append(f"| `{lit}` | {', '.join('`' + x + '`' for x in sorted(found[lit]))} |")
        body.append("")
    return write("redis-generated.md", "redis", "Redis Keys and Channels (generated)", "\n".join(body), check)


def redis_live():
    r = subprocess.run(["docker", "exec", "them-redis", "redis-cli", "--scan", "--count", "1000"], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("redis-cli failed: " + r.stderr.strip())
    static = set()
    for f in (ROOT / "go").rglob("*.go"):
        if "/vendor/" in f.as_posix() or f.name.endswith("_test.go"):
            continue
        static.update(KEYLIT.findall(f.read_text(encoding="utf-8")))
    seen = {}
    for k in r.stdout.split("\n"):
        if not k:
            continue
        pat = HEX.sub("{hex}", UUID.sub("{uuid}", k))
        pat = re.sub(r":\d{6,}", ":{n}", pat)
        seen[pat] = seen.get(pat, 0) + 1
    unknown = []
    for pat, n in sorted(seen.items()):
        if not any(pat.startswith(s.split("%")[0].split("{")[0]) for s in static if len(s) > 4):
            unknown.append((pat, n))
    print(f"{len(seen)} live key patterns; {len(unknown)} not matched by any literal prefix in the Go code:")
    for pat, n in unknown:
        print(f"  {pat}  (x{n})")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    chk = "--check" in sys.argv
    if cmd == "redis-live":
        sys.exit(redis_live())
    fn = {"routes": routes, "schema": schema, "node-types": node_types, "redis": redis}.get(cmd)
    sys.exit(fn(chk) if fn else __doc__)
