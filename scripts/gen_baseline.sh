#!/usr/bin/env bash
# Regenerate the fresh-install database baseline for the Slim package from a running
# the-M database (read-only: pg_dump + COPY ... TO STDOUT). Output: deploy/slim/db/.
#   ./scripts/gen_baseline.sh [container]      (default container: them-postgres)
# Baseline = schema (both schemas, owners + grants) + the few rows a new install needs.
# Anything created later by a db/NNN_*.sql migration is applied by deploy/slim/migrate.sh.
set -euo pipefail
C="${1:-them-postgres}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/deploy/slim/db"
mkdir -p "$OUT"
PSQL=(docker exec "$C" psql -U them -d them -At)

# Schema: keep owners (them_owner) and grants; skip nothing else.
docker exec "$C" pg_dump -U them -d them --schema-only -n them -n auth_service \
  | grep -v '^\\\(un\)\?restrict ' > "$OUT/100_schema.sql"

# Seed: global reference rows only (no demo apps/agents/users, no tenant-scoped data).
copy_block() { # <table> <select>
  echo "COPY $1 FROM stdin;"
  "${PSQL[@]}" -c "COPY ($2) TO STDOUT"
  echo '\.'
  echo
}
{
  echo "-- Generated by scripts/gen_baseline.sh from '$C' on $(date -u +%F). Do not edit by hand."
  echo "SET session_replication_role = replica;  -- load reference rows without FK ordering issues"
  copy_block them.tenants            "select * from them.tenants where is_bootstrap"
  copy_block auth_service.roles      "select * from auth_service.roles"
  copy_block them.config             "select * from them.config"
  copy_block them.middleware_defs    "select * from them.middleware_defs"
  copy_block them.component_definitions "select * from them.component_definitions where tenant_id is null"
  copy_block them.schema_migrations  "select * from them.schema_migrations"
  echo "SET session_replication_role = DEFAULT;"
} > "$OUT/200_seed.sql"

NEWEST=$("${PSQL[@]}" -c "select max(version) from them.schema_migrations")
echo "$NEWEST" > "$OUT/BASELINE_VERSION"
echo "baseline written to $OUT (newest migration recorded: $NEWEST)"
wc -l "$OUT"/*.sql
